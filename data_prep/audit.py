"""Audit the parsed IU reports and write data_prep/audit.md (aggregate statistics only).

    python -m data_prep.audit [--reports data/iu/reports.jsonl] [--out data_prep/audit.md]

The audit is committed, so it holds counts, shares and MeSH term frequencies only - never report
text (IU Open-i is CC BY-NC-ND). It answers: which sections are present, how often the de-id token
``XXXX`` appears, how long sections are, how many reports are "normal", and which findings dominate.
"""

from __future__ import annotations

import argparse
import json
import re
import statistics
from collections import Counter
from pathlib import Path

SECTIONS = ("indication", "comparison", "findings", "impression")
NORMAL_RE = re.compile(r"^normal$", re.IGNORECASE)


def load(path: Path) -> list[dict]:
    with open(path, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def is_normal(r: dict) -> bool:
    """IU codes a normal study as MeSH major ``normal``."""
    return any(NORMAL_RE.match(m.strip()) for m in r.get("mesh_major") or [])


def _pct(n: int, d: int) -> str:
    return f"{100.0 * n / d:.1f}%" if d else "n/a"


def _lens(rs: list[dict], key: str) -> list[int]:
    return [len((r.get(key) or "").split()) for r in rs if r.get(key)]


def audit(reports: list[dict]) -> str:
    n = len(reports)
    lines = ["# IU Open-i report audit", "",
             f"Generated by `python -m data_prep.audit` from `data/iu/reports.jsonl` ({n} reports).",
             "Aggregate statistics only: no report text is reproduced (licence CC BY-NC-ND 4.0).", "",
             "## Section presence and length (words)", "",
             "| Section | Present | Share | Median words | p95 words | Max | Contains `XXXX` |",
             "|---|---|---|---|---|---|---|"]
    for s in SECTIONS:
        present = [r for r in reports if r.get(s)]
        ls = sorted(_lens(reports, s))
        xx = sum(1 for r in present if "XXXX" in r[s])
        p95 = ls[int(0.95 * (len(ls) - 1))] if ls else 0
        lines.append(f"| {s} | {len(present)} | {_pct(len(present), n)} | "
                     f"{statistics.median(ls) if ls else 0:g} | {p95} | {max(ls) if ls else 0} | {_pct(xx, len(present))} |")

    both = sum(1 for r in reports if r.get("findings") and r.get("impression"))
    usable = sum(1 for r in reports if r.get("findings") or r.get("impression"))
    normal = sum(1 for r in reports if is_normal(r))
    exact = Counter(" ".join(((r.get("findings") or "") + " | " + (r.get("impression") or "")).lower().split())
                    for r in reports)
    dup_reports = sum(c for c in exact.values() if c > 1)
    lines += ["", "## Usability", "",
              f"- Reports with Findings AND Impression: {both} ({_pct(both, n)}).",
              f"- Reports with Findings OR Impression (renderable): {usable} ({_pct(usable, n)}).",
              f"- Reports coded MeSH major `normal`: {normal} ({_pct(normal, n)}).",
              (f"- Reports whose normalised Findings+Impression text is shared with at least one other report "
              f"(exact duplicates): {dup_reports} ({_pct(dup_reports, n)}) in {sum(1 for c in exact.values() if c > 1)} groups."),
              "  Near-duplicates (MinHash) are handled by `data_prep.split`; this is the exact-match floor.", ""]

    major = Counter(m.split("/")[0].strip().lower() for r in reports for m in (r.get("mesh_major") or []))
    lines += ["## Top 25 MeSH major terms (first qualifier level)", "", "| Term | Reports |", "|---|---|"]
    lines += [f"| {t} | {c} |" for t, c in major.most_common(25)]
    lines += ["", "## Implications for the build", "",
              ("- `XXXX` is IU's own de-identification token; it is kept as-is in rendered text (it is not PHI) "
              "and the PHI detector must not flag it."),
              "- Reports with neither Findings nor Impression are excluded from rendering.",
              ("- The large share of normal / exact-duplicate reports is why the split groups near-duplicates "
              "before stratifying (otherwise golden-set scores are inflated by memorised boilerplate)."), ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m data_prep.audit")
    ap.add_argument("--reports", type=Path, default=Path("data/iu/reports.jsonl"))
    ap.add_argument("--out", type=Path, default=Path("data_prep/audit.md"))
    a = ap.parse_args(argv)
    a.out.write_text(audit(load(a.reports)), encoding="utf-8")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
